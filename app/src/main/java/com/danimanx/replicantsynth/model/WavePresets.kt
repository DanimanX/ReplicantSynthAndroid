private fun wavePreset(
    name: String,
    category: String,
    baseNote: Int,
    bank: Int,
    position: Float,
    unison: Int,
    detune: Float,
    spread: Float,
    cutoff: Float,
    resonance: Float,
    drive: Float,
    attack: Float,
    decay: Float,
    sustain: Float,
    release: Float,
    sub: Float,
    noise: Float,
    level: Float,
    filterMode: Int,
    notes: IntArray,
): WavePreset = WavePreset(
    name = name,
    category = category,
    baseNote = baseNote,
    params = floatArrayOf(
        bank.toFloat(), position, unison.toFloat(), detune, spread, cutoff, resonance,
        drive, attack, decay, sustain, release, sub, noise, level, filterMode.toFloat(), 0f,
    ),
    notes = buildList {
        var i = 0
        while (i + 3 < notes.size) {
            val start = notes[i]
            val note = notes[i + 1]
            val velocity = notes[i + 2]
            val length = notes[i + 3]
            add(MidiNote(note = note, start = start, length = length, velocity = velocity))
            i += 4
        }
    },
)
